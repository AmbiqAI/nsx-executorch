# heliaAOT code generation for one delegated partition, plus the two small
# artifacts that connect the generated module to the ExecuTorch runtime:
#
# - <name>_et_registration.c: registers the module's init/run/IO accessors
#   with nsx-executorch's HeliaAotBackend registry (includes-api/
#   nsx_helia_aot.h) from a constructor. The module's CMakeLists adds it as an
#   INTERFACE source, so it is compiled into the application itself and the
#   linker cannot drop the registration.
# - the delegate blob stored in the PTE (blob.py): the module name and the
#   delegate's tensor contract, checked by the runtime at init and execute.

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional


DEFAULT_PLATFORM = "apollo510_evb"

# heliaAOT operator attributes that make the generated code compute exactly what ExecuTorch's kernels
# compute (the delegate's contract is bit-exactness with the non-delegated program):
# - HARD_SWISH: ExecuTorch runs arm_hard_swish_precise_s8; heliaAOT's int8 default is a lookup table.
SEMANTIC_OPERATOR_RULES = [
    {"type": "HARD_SWISH", "attributes": {"use_lut": False, "compat_variant": False}},
]

_REGISTRATION_TEMPLATE = """\
/*
 * Generated by helia-torch (nsx-executorch AOT) for the ExecuTorch helia-aot
 * delegate. Registers the heliaAOT module "{name}" with nsx-executorch's
 * HeliaAotBackend; the PTE's delegate blob names this module.
 */
#include <stddef.h>
#include <stdint.h>

#include "nsx_helia_aot.h"
#include "{name}_model.h"

static {name}_model_context_t {name}_et_context;

static int32_t {name}_et_init(void) {{ return {name}_model_init(&{name}_et_context); }}
static int32_t {name}_et_run(void) {{ return {name}_model_run(&{name}_et_context); }}

static void *{name}_et_input(uint32_t index) {{
    return index < {num_inputs}u ? (void *){name}_et_context.inputs[index].data : NULL;
}}

static void *{name}_et_output(uint32_t index) {{
    return index < {num_outputs}u ? (void *){name}_et_context.outputs[index].data : NULL;
}}

static const nsx_helia_aot_model_t {name}_et_model = {{
    .name = "{name}",
    .num_inputs = {num_inputs}u,
    .num_outputs = {num_outputs}u,
    .init = {name}_et_init,
    .run = {name}_et_run,
    .input = {name}_et_input,
    .output = {name}_et_output,
}};

__attribute__((constructor)) static void {name}_et_register(void) {{
    (void)nsx_helia_aot_register(&{name}_et_model);
}}
"""

_CMAKE_MARKER = "# helia-torch: ExecuTorch helia-aot delegate registration"


@dataclass
class HeliaAotOptions:
    """Where and for what to generate heliaAOT modules.

    output_dir: directory that receives one NSX module directory per delegated partition (required).
    platform: heliaAOT platform name (``helia-aot platforms list``).
    capabilities: optional platform capability override, e.g. ["MCU"] for a plain-C build that runs on a host.
    module_prefix: module names are ``<prefix>_<hash>``; the hash makes them unique and stable.
    """

    output_dir: Path
    platform: str = DEFAULT_PLATFORM
    capabilities: Optional[list[str]] = None
    module_prefix: str = "haot"
    extra: dict = field(default_factory=dict)  # deep-merged into heliaAOT's ConvertArgs


def compile_specs_for(options: HeliaAotOptions) -> list:
    from executorch.exir.backend.compile_spec_schema import CompileSpec

    specs = [
        CompileSpec("output_dir", str(options.output_dir).encode()),
        CompileSpec("platform", options.platform.encode()),
        CompileSpec("module_prefix", options.module_prefix.encode()),
    ]
    if options.capabilities is not None:
        specs.append(CompileSpec("capabilities", ",".join(options.capabilities).encode()))
    return specs


def options_from_specs(specs) -> HeliaAotOptions:
    values = {s.key: s.value.decode() for s in specs}
    if "output_dir" not in values:
        raise ValueError("HeliaAotBackend needs an output_dir compile spec (where to write the modules)")
    caps = values.get("capabilities")
    return HeliaAotOptions(
        output_dir=Path(values["output_dir"]),
        platform=values.get("platform", DEFAULT_PLATFORM),
        capabilities=caps.split(",") if caps else None,
        module_prefix=values.get("module_prefix", "haot"),
    )


def module_name_for(air_model, prefix: str) -> str:
    """A stable C identifier for a partition: prefix + a digest of its AIR."""
    name = f"{prefix}_{air_model.fingerprint()[:10]}"
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        raise ValueError(f"module_prefix {prefix!r} does not make a C identifier")
    return name


def generate_module(air_model, options: HeliaAotOptions, name: str) -> Path:
    """Run heliaAOT on `air_model` and write an NSX module `<output_dir>/<name>` wired for the delegate."""
    from helia_aot import AotConverter, ConvertArgs
    from helia_aot.cli.defines import OperatorRuleset
    from helia_aot.defines import ModuleType

    out_dir = Path(options.output_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    air_model.name = name
    args = dict(options.extra)
    cfg = ConvertArgs(**args) if args else ConvertArgs()
    cfg.model.name = name
    cfg.module.path = out_dir
    cfg.module.name = name
    cfg.module.prefix = name
    cfg.module.type = ModuleType.NSX
    cfg.platform.name = options.platform
    if options.capabilities is not None:
        from helia_aot.platforms.defines import SocCapability

        cfg.platform.capabilities = [SocCapability(c) for c in options.capabilities]
    present = {str(getattr(op.op_type, "name", op.op_type)) for op in air_model.operators}
    rules = [r for r in SEMANTIC_OPERATOR_RULES if r["type"] in present]
    cfg.operators = [OperatorRuleset(**rule) for rule in rules] + list(cfg.operators or [])
    cfg.force = True
    AotConverter(config=cfg).convert(model=air_model)
    module_dir = out_dir / name
    _write_registration(module_dir, name, len(air_model.input_ids), len(air_model.output_ids))
    return module_dir


def _write_registration(module_dir: Path, name: str, num_inputs: int, num_outputs: int) -> None:
    et_dir = module_dir / "et"
    et_dir.mkdir(exist_ok=True)
    (et_dir / f"{name}_et_registration.c").write_text(
        _REGISTRATION_TEMPLATE.format(name=name, num_inputs=num_inputs, num_outputs=num_outputs)
    )
    cmake = module_dir / "CMakeLists.txt"
    text = cmake.read_text()
    if _CMAKE_MARKER not in text:
        text += (
            f"\n{_CMAKE_MARKER}\n"
            "# Compiled into the consumer (INTERFACE) so the constructor that registers this module\n"
            "# with nsx-executorch's HeliaAotBackend is always linked.\n"
            f"target_sources({name} INTERFACE ${{CMAKE_CURRENT_LIST_DIR}}/et/{name}_et_registration.c)\n"
        )
        cmake.write_text(text)
