# heliaAOT code generation for one delegated partition, plus the two small
# artifacts that connect the generated module to the ExecuTorch runtime:
#
# - <name>_et_registration.c: registers the module's init/run/IO accessors
#   with nsx-executorch's HeliaAotBackend registry (includes-api/
#   nsx_helia_aot.h) from a constructor. The module's CMakeLists adds it as an
#   INTERFACE source, so it is compiled into the application itself and the
#   linker cannot drop the registration.
# - the delegate blob stored in the PTE (blob.py): the module name and the
#   delegate's tensor contract, checked by the runtime at init and execute.

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional


DEFAULT_PLATFORM = "apollo510_evb"

# heliaAOT operator attributes that make the generated code compute exactly what ExecuTorch's kernels
# compute (the delegate's contract is bit-exactness with the non-delegated program):
# - HARD_SWISH: ExecuTorch runs arm_hard_swish_precise_s8; heliaAOT's int8 default is a lookup table.
SEMANTIC_OPERATOR_RULES = [
    {"type": "HARD_SWISH", "attributes": {"use_lut": False, "compat_variant": False}},
]

_REGISTRATION_TEMPLATE = """\
/*
 * Generated by helia-torch (nsx-executorch AOT) for the ExecuTorch helia-aot
 * delegate. Registers the heliaAOT module "{name}" with nsx-executorch's
 * HeliaAotBackend; the PTE's delegate blob names this module.
 */
#include <stddef.h>
#include <stdint.h>

#include "nsx_helia_aot.h"
#include "{name}_model.h"

static {name}_model_context_t {name}_et_context;

static int32_t {name}_et_init(void) {{ return {name}_model_init(&{name}_et_context); }}
static int32_t {name}_et_run(void) {{ return {name}_model_run(&{name}_et_context); }}

static void *{name}_et_input(uint32_t index) {{
    return index < {num_inputs}u ? (void *){name}_et_context.inputs[index].data : NULL;
}}

static void *{name}_et_output(uint32_t index) {{
    return index < {num_outputs}u ? (void *){name}_et_context.outputs[index].data : NULL;
}}

static const nsx_helia_aot_model_t {name}_et_model = {{
    .name = "{name}",
    .num_inputs = {num_inputs}u,
    .num_outputs = {num_outputs}u,
    .init = {name}_et_init,
    .run = {name}_et_run,
    .input = {name}_et_input,
    .output = {name}_et_output,
}};

__attribute__((constructor)) static void {name}_et_register(void) {{
    (void)nsx_helia_aot_register(&{name}_et_model);
}}
"""

_CMAKE_MARKER = "# helia-torch: ExecuTorch helia-aot delegate registration"


@dataclass
class HeliaAotOptions:
    """Where and for what to generate heliaAOT modules.

    output_dir: directory that receives one NSX module directory per delegated partition (required).
    platform: heliaAOT platform name (``helia-aot platforms list``).
    capabilities: optional platform capability override, e.g. ["MCU"] for a plain-C build that runs on a host.
    module_prefix: module names are ``<prefix>_<program digest>_<partition>`` (see ``module_name_for``), and the
        saved program ``<prefix>_<program digest>.pt2``.
    debug_program: also save the program with its debug metadata, as ``<prefix>_<program digest>.debug.pt2``
        (see ``save_program``).
    """

    output_dir: Path
    platform: str = DEFAULT_PLATFORM
    capabilities: Optional[list[str]] = None
    module_prefix: str = "haot"
    debug_program: bool = False
    extra: dict = field(default_factory=dict)  # deep-merged into heliaAOT's ConvertArgs


#: Node metadata that records how a program was traced, not what it computes. PyTorch writes it differently on
#: every export of the same model, so a saved program is only reproducible without it.
_DEBUG_METADATA = ("from_node", "nn_module_stack", "stack_trace")


def save_program(program, options: HeliaAotOptions):
    """Save the quantized program the delegate converts to ``output_dir`` and return its file's source.

    Each delegated partition is a part of this file: heliaAOT's plan names the partition by the file's name, the
    SHA-256 of its bytes and the partition's index, so a plan made for it matches the same file again.

    The file, ``<prefix>_<digest>.pt2``, is the program without its debug metadata (``_DEBUG_METADATA``): the same
    quantized program then always saves to the same bytes, so exporting a model again gives the same digest, file
    and module names, while a program that differs in any weight or operator gets another. It loads with
    ``torch.export.load()`` and converts like the original. With ``options.debug_program`` the program is saved
    once more with its debug metadata, as ``<prefix>_<digest>.debug.pt2``; that copy is not what the digest names,
    and its bytes differ from one export to the next.
    """
    import copy

    import torch
    from helia_aot.air import AirModelSource

    out_dir = Path(options.output_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    reproducible = copy.deepcopy(program)  # the caller's program keeps its metadata
    for node in reproducible.graph.nodes:
        for key in _DEBUG_METADATA:
            node.meta.pop(key, None)
    staging = out_dir / f".{options.module_prefix}_program.pt2.tmp"
    torch.export.save(reproducible, staging)
    digest = AirModelSource.of_file(staging).sha256
    saved = out_dir / f"{options.module_prefix}_{digest[:10]}.pt2"
    staging.replace(saved)
    if options.debug_program:
        torch.export.save(program, saved.with_suffix(".debug.pt2"))
    return AirModelSource(file=saved.name, sha256=digest)


def compile_specs_for(options: HeliaAotOptions, source=None, partition: int = 0) -> list:
    """The delegate's compile specs: ``options``, and the program file ``source`` with the partition's index."""
    from executorch.exir.backend.compile_spec_schema import CompileSpec

    specs = [
        CompileSpec("output_dir", str(options.output_dir).encode()),
        CompileSpec("platform", options.platform.encode()),
        CompileSpec("module_prefix", options.module_prefix.encode()),
    ]
    if source is not None:
        specs += [
            CompileSpec("source_file", source.file.encode()),
            CompileSpec("source_sha256", source.sha256.encode()),
            CompileSpec("partition", str(partition).encode()),
        ]
    if options.capabilities is not None:
        specs.append(CompileSpec("capabilities", ",".join(options.capabilities).encode()))
    return specs


def options_from_specs(specs) -> HeliaAotOptions:
    values = {s.key: s.value.decode() for s in specs}
    if "output_dir" not in values:
        raise ValueError("HeliaAotBackend needs an output_dir compile spec (where to write the modules)")
    caps = values.get("capabilities")
    return HeliaAotOptions(
        output_dir=Path(values["output_dir"]),
        platform=values.get("platform", DEFAULT_PLATFORM),
        capabilities=caps.split(",") if caps else None,
        module_prefix=values.get("module_prefix", "haot"),
    )


def source_from_specs(specs):
    """The partition's source: the saved program file (its name and SHA-256) and the partition's index."""
    from helia_aot.air import AirModelSource

    values = {s.key: s.value.decode() for s in specs}
    missing = [key for key in ("source_file", "source_sha256", "partition") if key not in values]
    if missing:
        raise ValueError(
            f"HeliaAotBackend needs the {', '.join(missing)} compile spec(s): the program file the partition is "
            "part of (HeliaAotPartitioner sets them from save_program())"
        )
    return AirModelSource(
        file=values["source_file"], sha256=values["source_sha256"], subgraph=int(values["partition"])
    )


def module_name_for(source, prefix: str) -> str:
    """The partition's C identifier: prefix, the program file's digest and the partition's index."""
    name = f"{prefix}_{source.sha256[:10]}_{source.subgraph}"
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        raise ValueError(f"module_prefix {prefix!r} does not make a C identifier")
    return name


def apply_semantic_rules(cfg, air_model) -> None:
    """Prepend SEMANTIC_OPERATOR_RULES for the operators `air_model` uses to heliaAOT ConvertArgs `cfg`."""
    from helia_aot.cli.defines import OperatorRuleset

    present = {str(getattr(op.op_type, "name", op.op_type)) for op in air_model.operators}
    rules = [r for r in SEMANTIC_OPERATOR_RULES if r["type"] in present]
    cfg.operators = [OperatorRuleset(**rule) for rule in rules] + list(cfg.operators or [])


def convert_air(air_model, cfg):
    """Run heliaAOT on `air_model` with ConvertArgs `cfg` (module, platform, memory, ...) and return its
    ConversionResult. The semantic operator rules (bit-exactness with ExecuTorch's kernels) are applied first,
    to a copy of `cfg`: the caller's configuration is unchanged, so it can be used again.

    `air_model.source` must name the file the model was converted from: heliaAOT's plan identifies the model by
    it. program_to_air(..., source=AirModelSource.of_file(<the saved .pt2>)) sets it.
    """
    from helia_aot import AotConverter

    if air_model.source is None:
        raise ValueError(
            "convert_air: the AIR model has no source. Save the quantized program (torch.export.save) and pass "
            "program_to_air(..., source=helia_aot.air.AirModelSource.of_file(<that file>)), or set air.source."
        )
    cfg = cfg.model_copy(deep=True)
    apply_semantic_rules(cfg, air_model)
    return AotConverter(config=cfg).convert(air_model)


def generate_module(air_model, options: HeliaAotOptions, name: str, *, executorch_registration: bool = True) -> Path:
    """Run heliaAOT on `air_model` and write the NSX module `<output_dir>/<name>`.

    With executorch_registration (the delegate), the module also registers itself with nsx-executorch's
    HeliaAotBackend; without it (compile_model), it is a plain heliaAOT module.
    """
    from helia_aot import ConvertArgs
    from helia_aot.defines import ModuleType

    out_dir = Path(options.output_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    air_model.name = name
    args = dict(options.extra)
    cfg = ConvertArgs(**args) if args else ConvertArgs()
    cfg.model.name = name
    cfg.module.path = out_dir
    cfg.module.name = name
    cfg.module.prefix = name
    cfg.module.type = ModuleType.NSX
    cfg.platform.name = options.platform
    if options.capabilities is not None:
        from helia_aot.platforms.defines import SocCapability

        cfg.platform.capabilities = [SocCapability(c) for c in options.capabilities]
    cfg.force = True
    convert_air(air_model, cfg)
    module_dir = out_dir / name
    if executorch_registration:
        _write_registration(module_dir, name, len(air_model.input_ids), len(air_model.output_ids))
    return module_dir


def _write_registration(module_dir: Path, name: str, num_inputs: int, num_outputs: int) -> None:
    et_dir = module_dir / "et"
    et_dir.mkdir(exist_ok=True)
    (et_dir / f"{name}_et_registration.c").write_text(
        _REGISTRATION_TEMPLATE.format(name=name, num_inputs=num_inputs, num_outputs=num_outputs)
    )
    cmake = module_dir / "CMakeLists.txt"
    text = cmake.read_text()
    if _CMAKE_MARKER not in text:
        text += (
            f"\n{_CMAKE_MARKER}\n"
            "# Compiled into the consumer (INTERFACE) so the constructor that registers this module\n"
            "# with nsx-executorch's HeliaAotBackend is always linked.\n"
            f"target_sources({name} INTERFACE ${{CMAKE_CURRENT_LIST_DIR}}/et/{name}_et_registration.c)\n"
        )
        cmake.write_text(text)
